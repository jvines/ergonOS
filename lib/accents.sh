# Press-and-hold accents: the person's choices, and the one render that turns
# them and the repo's defaults into the file fcitx5 reads (ERGON-79).
#
# Sourced by bin/ergon-accents and install.sh. Not a command; nothing execs
# this. Needs $ERGON set to the checkout.
#
# Two inputs with two owners, and one output:
#
#   fcitx5/omacento.conf        the repo's: the table, Language, and the
#                               defaults for Enabled and HoldTime
#   ~/.config/ergon/accents     the person's: what `ergon accents` was told --
#                               on or off, the hold, the classes to skip
#   ~/.config/fcitx5/conf/omacento.conf
#                               what fcitx5 reads. GENERATED from the two by
#                               ergon_accents_render and by nothing else, on
#                               every sync and on every `ergon accents` change
#
# It was a link into the checkout, so the only way to turn the popup off was
# an edit to a repo-owned file -- which the next pull either kept as a dirty
# tree or threw away. Rendered, a sync never undoes a choice and a change to
# the table still reaches someone who made one.
#
# ~/.config/ergon/accents is DATA, never sourced: `key=value` lines, `skip=`
# once per window class, `#` comments. This file is the only code that writes
# it, and ergon-lint holds every other file to that. Unlike the include stubs
# lib/user-config.sh creates, it IS rewritten -- it is a command's own settings
# file, written when the person runs that command -- so the write is surgical:
# the one key asked about changes, in place, and every other line stays,
# comments and hand edits included. Nothing creates it until a command does;
# with no file, every setting is the repo's default.

ergon_accents_prefs() { printf '%s/ergon/accents\n' "${XDG_CONFIG_HOME:-$HOME/.config}"; }
ergon_accents_live()  { printf '%s/fcitx5/conf/omacento.conf\n' "${XDG_CONFIG_HOME:-$HOME/.config}"; }
ergon_accents_src()   { printf '%s/fcitx5/omacento.conf\n' "$ERGON"; }

# The first line of every render, and how a render knows the file is its own.
# A file without it is someone else's -- fcitx5's settings window writes this
# file too, without comments -- and is never written over.
ERGON_ACCENTS_MARK='# GENERATED by lib/accents.sh -- run `ergon accents` to change it, not this file'

ERGON_ACCENTS_HEADER='# Press-and-hold accents: what `ergon accents` has been told (ERGON-79).
# One setting a line -- enabled=on|off, hold=<ms, 100 to 1000>, and
# skip=<window class> once per class. Hand edits are kept; `ergon accents`
# with no arguments shows what is in effect, and any change applies them.
# Anything not set here is the default in the repo, fcitx5/omacento.conf.'

# --- reading ------------------------------------------------------------------

# Every value given for <key>, in order. Blank and comment lines are skipped;
# blanks around the key and the value are not part of either.
_ergon_accents_values() {  # <key>
  local f
  f=$(ergon_accents_prefs)
  [ -f "$f" ] || return 0
  awk -v k="$1" '
    /^[[:space:]]*(#|$)/ { next }
    { i = index($0, "="); if (!i) next
      key = substr($0, 1, i - 1); val = substr($0, i + 1)
      gsub(/^[[:space:]]+|[[:space:]]+$/, "", key)
      gsub(/^[[:space:]]+|[[:space:]]+$/, "", val)
      if (key == k) print val }' "$f"
}

# A top-level key of the repo's file: the part before its first [section].
_ergon_accents_default() {  # <Key>
  awk -v k="$1" '
    /^\[/ { exit }
    index($0, k "=") == 1 { v = substr($0, length(k) + 2) }
    END { print v }' "$(ergon_accents_src)" 2>/dev/null
}

ergon_accents_valid_hold() {  # <ms>: what omacento accepts (IntConstrain 100..1000)
  [[ ${1:-} =~ ^[0-9]{1,4}$ ]] && [ "$((10#$1))" -ge 100 ] && [ "$((10#$1))" -le 1000 ]
}

# A window class that can be written into fcitx5's INI as a bare value and
# come back out the same: no control characters, no quotes or backslashes
# (which fcitx5 would escape, and gdbus would print escaped), no blanks at
# either end. Every class Hyprland has reported on this machine qualifies.
ergon_accents_valid_class() {  # <class>
  local LC_ALL=C
  [[ -n ${1:-} && $1 != *[[:cntrl:]]* && $1 != *[\"\'\\]* \
     && $1 != [[:space:]]* && $1 != *[[:space:]] ]]
}

# The settings in effect: the LAST value of each that makes sense, otherwise
# the repo's. A value that does not make sense is named on stderr and passed
# over, rather than handed to fcitx5 to reject silently -- a typo added below a
# good line costs that line nothing.
ergon_accents_enabled() {  # -> on | off
  local v best=""
  while IFS= read -r v; do
    case "$v" in
      on|yes|true|True)   best=on ;;
      off|no|false|False) best=off ;;
      *) printf 'ergon accents: ignoring enabled=%s in %s (on or off)\n' "$v" "$(ergon_accents_prefs)" >&2 ;;
    esac
  done < <(_ergon_accents_values enabled)
  [ -z "$best" ] || { echo "$best"; return; }
  case "$(_ergon_accents_default Enabled)" in False|false) echo off ;; *) echo on ;; esac
}

ergon_accents_hold() {  # -> milliseconds
  local v best=""
  while IFS= read -r v; do
    if ergon_accents_valid_hold "$v"; then
      best=$((10#$v))
    else
      printf 'ergon accents: ignoring hold=%s in %s (100 to 1000)\n' "$v" "$(ergon_accents_prefs)" >&2
    fi
  done < <(_ergon_accents_values hold)
  [ -z "$best" ] || { echo "$best"; return; }
  v=$(_ergon_accents_default HoldTime)
  if ergon_accents_valid_hold "$v"; then echo "$((10#$v))"; else echo 250; fi
}

ergon_accents_skips() {  # -> each class to skip, once, in the order given
  local c
  declare -A seen=()
  while IFS= read -r c; do
    [ -n "$c" ] || continue
    if ! ergon_accents_valid_class "$c"; then
      printf 'ergon accents: ignoring skip=%s in %s (not a class fcitx5 can match)\n' "$c" "$(ergon_accents_prefs)" >&2
      continue
    fi
    [ -z "${seen[$c]:-}" ] || continue
    seen[$c]=1
    printf '%s\n' "$c"
  done < <(_ergon_accents_values skip)
}

# --- writing the person's file --------------------------------------------------

# Rewrites the prefs file through an awk program, creating it with its header
# first if there is none. Through the file rather than renamed over it: someone
# who made it a link into their own dotfiles has answered where it lives, and a
# rename would replace that link with a copy.
_ergon_accents_edit() {  # <awk args...>
  local f tmp
  f=$(ergon_accents_prefs)
  mkdir -p "$(dirname "$f")" || return 1
  [ -e "$f" ] || printf '%s\n' "$ERGON_ACCENTS_HEADER" > "$f" || return 1
  tmp=$(mktemp) || return 1
  if awk "$@" "$f" > "$tmp" && cat "$tmp" > "$f"; then
    rm -f "$tmp"
  else
    rm -f "$tmp"; return 1
  fi
}

# One line for <key>, where its first one was, or at the end.
ergon_accents_set() {  # <key> <value>
  _ergon_accents_edit -v k="$1" -v val="$2" '
    function keyof(s,   i, kk) { if (s ~ /^[[:space:]]*#/) return ""
      i = index(s, "="); if (!i) return ""
      kk = substr(s, 1, i - 1); gsub(/^[[:space:]]+|[[:space:]]+$/, "", kk); return kk }
    keyof($0) == k { if (!done) print k "=" val; done = 1; next }
    { print }
    END { if (!done) print k "=" val }'
}

ergon_accents_skip_add() {  # <class>
  _ergon_accents_edit -v c="$1" '
    function valof(s,   i, v) { i = index(s, "="); v = substr(s, i + 1)
      gsub(/^[[:space:]]+|[[:space:]]+$/, "", v); return v }
    $0 !~ /^[[:space:]]*#/ && $0 ~ /^[[:space:]]*skip[[:space:]]*=/ && valof($0) == c { have = 1 }
    { print }
    END { if (!have) print "skip=" c }'
}

ergon_accents_skip_del() {  # <class>: every skip= line that names it
  _ergon_accents_edit -v c="$1" '
    function valof(s,   i, v) { i = index(s, "="); v = substr(s, i + 1)
      gsub(/^[[:space:]]+|[[:space:]]+$/, "", v); return v }
    $0 !~ /^[[:space:]]*#/ && $0 ~ /^[[:space:]]*skip[[:space:]]*=/ && valof($0) == c { next }
    { print }'
}

# --- the render -------------------------------------------------------------------

# The file fcitx5 reads, on stdout. INI as fcitx5 itself writes it: every
# top-level key before the first [section] -- a key belongs to the last header
# above it, so Enabled written after [Table] would be read as a table row and
# the setting left at its default -- and a list as a [section] of 0=, 1=, ...
# The repo's own Enabled and HoldTime, and any [Blocklist] in it, are dropped:
# the values in effect replace them.
ergon_accents_compose() {
  local en hold skips
  en=$( [ "$(ergon_accents_enabled)" = on ] && echo True || echo False )
  hold=$(ergon_accents_hold)
  skips=$(ergon_accents_skips)
  printf '%s\n' "$ERGON_ACCENTS_MARK"
  printf '# Rendered from %s\n# and %s.\n' "$(ergon_accents_src)" "$(ergon_accents_prefs)"
  printf 'Enabled=%s\nHoldTime=%s\n\n' "$en" "$hold"
  ERGON_ACCENTS_SKIPLIST="$skips" awk '
    BEGIN { top = 1 }
    /^\[/ { top = 0
            drop = ($0 ~ /^\[Blocklist(\]|\/)/)
            if (drop) next }
    drop { next }
    top && /^(Enabled|HoldTime)[[:space:]]*=/ { next }
    { print }
    END {
      print ""
      print "[Blocklist]"
      n = split(ENVIRON["ERGON_ACCENTS_SKIPLIST"], s, "\n")
      j = 0
      for (i = 1; i <= n; i++) if (s[i] != "") print (j++) "=" s[i]
    }' "$(ergon_accents_src)"
}

# Writes the render where fcitx5 reads it. Sets ERGON_ACCENTS_DID to one of
#   unchanged      the file already said exactly this
#   written        it did not, and now does
#   replaced-link  it was the old link into the checkout; it is a file now
# and returns 3, writing nothing, when the file there is not a render of ours.
ergon_accents_render() {
  local out tmp
  out=$(ergon_accents_live)
  ERGON_ACCENTS_DID=""
  [ -f "$(ergon_accents_src)" ] || { printf 'ergon accents: %s is missing\n' "$(ergon_accents_src)" >&2; return 1; }
  if [ ! -L "$out" ] && [ -e "$out" ] && [ "$(head -1 "$out" 2>/dev/null)" != "$ERGON_ACCENTS_MARK" ]; then
    printf 'ergon accents: %s is not a render of ours (fcitx5'"'"'s settings window writes one like it); move it aside and run: ergon accents\n' "$out" >&2
    return 3
  fi
  mkdir -p "$(dirname "$out")" || return 1
  tmp=$(mktemp "$out.XXXXXX") || return 1
  ergon_accents_compose > "$tmp" || { rm -f "$tmp"; return 1; }
  if [ -L "$out" ]; then
    ERGON_ACCENTS_DID=replaced-link
  elif cmp -s "$tmp" "$out"; then
    rm -f "$tmp"; ERGON_ACCENTS_DID=unchanged; return 0
  else
    ERGON_ACCENTS_DID=written
  fi
  chmod 644 "$tmp"
  # A rename replaces a link itself rather than writing through it, which is
  # the point when the link is the old one into the checkout.
  mv -f "$tmp" "$out"
}

# --- the running fcitx5 ---------------------------------------------------------

# The session bus, found the way a login gets it when this runs without one in
# its environment (install.sh under su, a cron job): the user manager's socket.
_ergon_accents_bus() {
  if [ -n "${DBUS_SESSION_BUS_ADDRESS:-}" ]; then
    printf '%s\n' "$DBUS_SESSION_BUS_ADDRESS"
  elif [ -S "/run/user/$(id -u)/bus" ]; then
    printf 'unix:path=/run/user/%s/bus\n' "$(id -u)"
  fi
}

_ergon_accents_call() {  # <method> [args...]
  DBUS_SESSION_BUS_ADDRESS="$(_ergon_accents_bus)" timeout 10 gdbus call --session \
    --dest org.fcitx.Fcitx5 --object-path /controller \
    --method "org.fcitx.Fcitx.Controller1.$1" "${@:2}" 2>&1
}

# Whether omacento's live configuration (GetConfig, as gdbus prints it) holds
# the settings in effect. The one comparison status and apply both make.
ergon_accents_live_matches() {  # <GetConfig output>
  local cfg=$1 en want c i=0
  en=$( [ "$(ergon_accents_enabled)" = on ] && echo True || echo False )
  [[ $cfg == *"'Enabled': <'$en'>"* ]] || return 1
  [[ $cfg == *"'HoldTime': <'$(ergon_accents_hold)'>"* ]] || return 1
  want=""
  while IFS= read -r c; do
    [ -n "$c" ] || continue
    want="${want:+$want, }'$i': <'$c'>"; i=$((i + 1))
  done < <(ergon_accents_skips)
  if [ -z "$want" ]; then
    [[ $cfg == *"'Blocklist': <''>"* ]]
  else
    [[ $cfg == *"'Blocklist': <{$want}>"* ]]
  fi
}

# Makes the running fcitx5 read the render, and checks that it did.
#   0  applied: omacento reports exactly the settings in effect
#   1  no fcitx5 of this user's is running; it reads the file when it starts
#   2  one is running and does not report them
#
# ReloadAddonConfig omacento, not `fcitx5-remote -r`: that is ReloadConfig,
# which re-reads fcitx5's GLOBAL config and no addon's (Instance::reloadConfig).
# Measured both ways against 5.1.23 and omacento 1.1.1, 2026-10-13. And never a
# call when no fcitx5 is running: a call to org.fcitx.Fcitx5 STARTS one, by
# D-Bus activation, outside the session.
ergon_accents_apply() {
  local cfg
  pgrep -u "$(id -u)" -x fcitx5 >/dev/null 2>&1 || return 1
  _ergon_accents_call ReloadAddonConfig omacento >/dev/null || return 2
  cfg=$(_ergon_accents_call GetConfig fcitx://config/addon/omacento) || return 2
  ergon_accents_live_matches "$cfg" || return 2
}
